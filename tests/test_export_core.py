def test_deadline_also_holds_off_the_main_thread():
    import threading

    box = {}

    def go():
        try:
            registry.render(
                "{% for i in range(90000) %}{% for j in range(90000) %}{% endfor %}{% endfor %}",
                {},
                timeout_s=0.3,
            )
        except ExportError as exc:
            box["err"] = exc

