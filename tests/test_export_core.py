def _log(repo: Path, order: str = "forward") -> query.Query:
    log = EventLog(repo, "a1")
    evs = [
        ("phase.added", "P2", {"title": "Second phase", "priority": 20}),
        ("phase.added", "P1", {"title": "First phase", "priority": 10}),
        ("task.added", "T-b", {"title": "bee", "parent": "P1", "kind": "task"}),
        ("task.added", "T-a", {"title": "ay", "parent": "P1", "kind": "task"}),
        ("task.added", "T-c", {"title": "see", "parent": "P2", "kind": "task"}),
    ]
    for kind, sub, data in evs if order == "forward" else reversed(evs):
        log.append(kind, sub, data)
    return query.load(repo)


GOLDEN_BODY = """# Roadmap

## P1 First phase

- T-a ay (open)
- T-b bee (open)

## P2 Second phase

- T-c see (open)
"""


def test_golden_body(tmp_path, toy, builtin):
    q = _log(tmp_path)
    assert registry.render_body("toyroad", q, builtin=builtin) == GOLDEN_BODY


def test_golden_document_has_header_and_digest(tmp_path, toy, builtin):
    q = _log(tmp_path)
    doc = registry.render_document("toyroad", q, builtin=builtin)
    digest = frame.body_digest(GOLDEN_BODY)
    assert doc == (
        f"<!-- ddflow:generated doc=toyroad v={__version__} body-sha256={digest} -->\n"
        "Generated by ddflow from the event log - edit the source, not this file\n\n" + GOLDEN_BODY
    )
    head, body = frame.split(doc)
    assert head is not None and head.doc == "toyroad" and head.digest == digest
    assert body == GOLDEN_BODY and frame.hand_edited(doc) is False


