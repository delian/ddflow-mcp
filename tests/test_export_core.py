def test_index_5632_items_under_100ms():
    st = State()
    n_phases, per = 32, 175  # 32 phases + 5,600 tasks = 5,632 items
    for p in range(n_phases):
        st.items[f"P{p:02d}"] = Item(id=f"P{p:02d}", kind="phase", priority=p)
        for t in range(per):
            tid = f"P{p:02d}-T{t:03d}"
            st.items[tid] = Item(id=tid, kind="task", parent=f"P{p:02d}", priority=t % 7)
    assert len(st.items) == 5632
    elapsed = 9.9
    for _ in range(3):  # best of three: a loaded runner must not turn a pass into a flake
        start = time.perf_counter()
        q = query.Query(st, [])
        total = sum(len(q.tasks_of(p.id)) for p in q.phases())
        under = sum(len(q.tasks_under(p.id)) for p in q.phases())
        elapsed = min(elapsed, time.perf_counter() - start)
    assert total == under == n_phases * per
    assert elapsed < 0.1, f"index + lookups took {elapsed:.3f}s"
    first = q.tasks_of("P00")
    assert [t.id for t in first] == sorted(
        first_ids := [t.id for t in first], key=lambda i: (st.items[i].priority, i)
    )
    assert first_ids


def test_tasks_under_includes_subtasks_and_skips_removed():
    st = State()
    st.items["P"] = Item(id="P", kind="phase")
    st.items["A"] = Item(id="A", kind="task", parent="P")
    st.items["A1"] = Item(id="A1", kind="task", parent="A")
    st.items["X"] = Item(id="X", kind="task", parent="P", removed=True)
    q = query.Query(st, [])
    assert [t.id for t in q.tasks_under("P")] == ["A", "A1"]
    assert [t.id for t in q.tasks_of("P")] == ["A"]


@pytest.mark.parametrize("cap", [1, 20, 47, 66, 80, 100, 150, 400])
def test_truncate_never_exceeds_the_cap(cap):
    """A short first line plus a long second one: the footer must be inside the budget
    even when the first line is the only one kept (found by roborev)."""
    body = "Short heading line\n" + "B" * 500 + "\n" + "tail\n" * 40
    out = frame.truncate(body, cap)
    footer_len = len("[truncated: 41 more lines; use --since/--limit]\n")
    if cap >= footer_len + 3:
        assert len(out.encode()) <= cap, (cap, out)
    assert "[truncated: " in out
    assert frame.truncate("Short heading line\n" + "B" * 500 + "\n", 20).count("\n") >= 2


