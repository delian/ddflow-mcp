TEMPLATE = """# Roadmap
{% for p in phases %}

## {{ p.id }} {{ p.title }}

{% for t in p.tasks %}
- {{ t.id }} {{ t.title }} ({{ t.state }})
{% endfor %}
{% endfor %}
"""


def _data(q: query.Query, f: Filters) -> dict:
    phases = [
        {
            "id": p.id,
            "title": frame.one_line(p.title),
            "tasks": [
                {"id": t.id, "title": frame.one_line(t.title), "state": t.state}
                for t in q.tasks_of(p.id)
            ][: f.limit or None],
        }
        for p in q.phases()
    ]
    return {"phases": phases}


