def test_template_resolution_order(tmp_path, toy, builtin):
    q = _log(tmp_path)
    assert registry.resolve_template("toyroad", tmp_path, builtin=builtin).source == "builtin"
    proj = tmp_path / ".ddflow" / "templates" / "export"
    proj.mkdir(parents=True)
    (proj / "toyroad.md.j2").write_text("PROJECT {{ phases|length }}\n")
    t = registry.resolve_template("toyroad", tmp_path, builtin=builtin)
    assert t.source == "project"
    assert registry.render_body("toyroad", q, repo=tmp_path, builtin=builtin) == "PROJECT 2\n"
    (tmp_path / "mine.j2").write_text("CONFIG\n")
    t = registry.resolve_template("toyroad", tmp_path, {"toyroad": "mine.j2"}, builtin)
    assert t.source == "config"
    with pytest.raises(ExportError):  # a configured path that is missing is an error
        registry.resolve_template("toyroad", tmp_path, {"toyroad": "gone.j2"}, builtin)


