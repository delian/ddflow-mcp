"""The bar a duplicate detector must clear, on ddflow's own records (B-dedupe-evalset).

The fixture (tests/fixtures/dedupe/) is a redacted snapshot of every bug, task and phase
in ddflow's event log (``corpus.jsonl``, regenerated by ``build_fixture.py``) and a
hand-verified label set (``pairs.jsonl``): pairs that are the same defect or the same work
(``duplicate``), pairs a filer should be SHOWN (``related``: a follow-up, a residual, a
root-cause link) and pairs that look alike but are distinct defects (``hard_negative``:
same function, same review, same fix batch). Decision D-no-duplicates, research
R-dedupe-matchers.

Every pair is scored the way an add sees it: the LATER record is the query, and its
candidates are the records of its group (bugs among bugs; tasks and phases among
items) that existed before it. The bar, from B-similar-engine's acceptance:

- duplicates: the earlier record ranks in the top 3 for >= 95% of pairs;
- related: in the top 5 for >= 90%;
- lenient precision at the ask threshold: of every (record, earlier record) pair scoring
  >= ASK_THRESHOLD, >= 75% are labelled duplicate or related;
- hard negatives: <= 20% score >= ASK_THRESHOLD.

The engine interface this file fixes for B-similar-engine (``ddflow.services.similar``):

    index = similar.build(records)        # records: mappings with id, kind, title, body
    hits = index.query(record, limit=None)  # record: a mapping with kind, title, body
    # -> list[tuple[str, float]], best first, scores in [0, 1]; limit=None means every
    #    candidate the engine scores above zero. The query's own id, if indexed, may be
    #    returned; the evaluation drops it. A record missing from hits scores 0.

``test_the_engine_meets_the_bar`` is a strict xfail until that module exists: it starts
failing loudly the day the engine passes, and B-similar-engine removes the mark.
``test_the_reference_matcher_meets_the_bar`` proves the bar is reachable on this fixture
with the research's stdlib TF-IDF, and that the metric code itself is sound.
"""

from __future__ import annotations

import collections
import importlib
import itertools
import json
import math
import re
import sys
from pathlib import Path

import pytest

from tests.test_repo_is_generic import _private_addresses

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "dedupe"

#: [dedupe].ask_threshold's default in D-no-duplicates. Change both together.
ASK_THRESHOLD = 0.55
BAR = {"dup_r3": 0.95, "rel_r5": 0.90, "lenient_p": 0.75, "hard_above": 0.20}
#: Below this share of duplicates at the ask threshold, precision measures nothing: an
#: engine that never asks would be "precise". The research's matcher asks on ~half.
MIN_DUP_ASKED = 0.25
RELATIONS = ("duplicate", "related", "hard_negative")
KINDS = ("bug", "task", "phase")
MAX_FIXTURE_BYTES = 1_000_000


def _jsonl(name: str) -> list[dict]:
    lines = (FIXTURE / name).read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in lines if line.strip()]


CORPUS = _jsonl("corpus.jsonl")
PAIRS = _jsonl("pairs.jsonl")
BY_ID = {r["id"]: r for r in CORPUS}


def _group(rec: dict) -> str:
    return "bug" if rec["kind"] == "bug" else "item"


def _order(rec: dict) -> tuple[str, str]:
    return (rec["added"], rec["id"])


# --------------------------------------------------------------------- fixture integrity


def test_the_corpus_is_well_formed():
    assert len(CORPUS) >= 500, "the corpus is a snapshot of the whole log, distractors included"
    assert len(BY_ID) == len(CORPUS), "an id appears twice in the corpus"
    for r in CORPUS:
        assert set(r) == {"id", "kind", "title", "body", "state", "added"}, r["id"]
        assert r["kind"] in KINDS, r["id"]
        assert r["title"] or r["body"], r["id"]
        assert re.fullmatch(r"\d{4}-\d\d-\d\dT[\d:.]+Z", r["added"]), r["id"]


def test_the_labels_are_well_formed_and_name_corpus_records():
    seen: dict[frozenset, str] = {}
    for p in PAIRS:
        assert set(p) == {"relation", "a", "b", "reason"}, p
        assert p["relation"] in RELATIONS, p
        assert p["a"] < p["b"], f"a pair is written sorted: {p}"
        assert p["reason"].strip(), p
        assert p["a"] in BY_ID and p["b"] in BY_ID, f"labelled id not in the corpus: {p}"
        assert _group(BY_ID[p["a"]]) == _group(BY_ID[p["b"]]), f"pair crosses groups: {p}"
        key = frozenset((p["a"], p["b"]))
        assert key not in seen, f"pair labelled twice ({seen.get(key)} and {p['relation']}): {p}"
        seen[key] = p["relation"]
    counts = collections.Counter(p["relation"] for p in PAIRS)
    assert counts["duplicate"] >= 40 and counts["related"] >= 17 and counts["hard_negative"] >= 18


def test_duplicates_are_transitive():
    """Same-defect is an equivalence: if a~b and b~c are duplicates, a~c must be labelled
    one too, or the scorer would count a correct candidate as a false ask."""
    dup = {frozenset((p["a"], p["b"])) for p in PAIRS if p["relation"] == "duplicate"}
    nodes = {x for pair in dup for x in pair}
    for a, b, c in itertools.permutations(sorted(nodes), 3):
        if frozenset((a, b)) in dup and frozenset((b, c)) in dup:
            assert frozenset((a, c)) in dup, f"{a}~{b}~{c} but {a}~{c} is not labelled"


def test_the_fixture_is_redacted():
    """Decision D-no-own-services-local-dir: no private host, served model name or home
    directory reaches the committed fixture -- checked here as well as by
    test_repo_is_generic, so the reason names this fixture's own redactor."""
    sys.path.insert(0, str(FIXTURE))
    try:
        build = importlib.import_module("build_fixture")
    finally:
        sys.path.remove(str(FIXTURE))
    size = sum((FIXTURE / n).stat().st_size for n in ("corpus.jsonl", "pairs.jsonl"))
    assert size < MAX_FIXTURE_BYTES, f"fixture is {size} bytes; keep it modest"
    for r in CORPUS + PAIRS:
        for field in ("title", "body", "reason"):
            text = r.get(field, "")
            assert not _private_addresses(text), (r.get("id") or r, _private_addresses(text))
            assert not build.MODEL_NAME.search(text), (r.get("id") or r, field)
            assert not build.HOME.search(text), (r.get("id") or r, field)
            # A fixed point: the committed text is exactly what the redactor emits. The
            # host pass is off (host=""), so the check is a property of the file, not of
            # the machine running it; build() masks the generating host's name.
            assert build.redact(text, host="") == text, (r.get("id") or r, field)


def test_the_redactor_masks_what_it_promises():
    sys.path.insert(0, str(FIXTURE))
    try:
        build = importlib.import_module("build_fixture")
    finally:
        sys.path.remove(str(FIXTURE))
    lan = ".".join(("10", "9", "8", "7"))
    raw = (
        f"critic at http://{lan}:8000/v1 serving acme/Qwen9.9-99B-it on box7 "
        "(/home/someone/src) with api_key=abc123; local 127.0.0.1 and the LAN Qwen stay"
    )
    out = build.redact(raw, host="box7")
    assert lan not in out and "Qwen9.9" not in out and "box7" not in out
    assert "someone" not in out and "abc123" not in out
    assert "127.0.0.1" in out and "the LAN Qwen stay" in out
    assert build.redact(out, host="box7") == out
    # A host whose name is a word in the markers leaves the markers alone.
    markers = "<lan-address> <served-model> <host> /home/user/ [REDACTED]"
    for host in ("host", "lan", "address", "served", "model", "user", "home", "redacted"):
        assert build.redact(markers, host=host) == markers, host
    # A served name ending in its version digit is a served name too.
    for name in ("qwen2", "gpt-4", "llama3", "deepseek-v3", "phi-3", "qwen3:8b"):
        assert (
            build.redact(f"routed to {name}: today", host="") == "routed to <served-model>: today"
        )


def test_the_builder_folds_the_log_into_redacted_records(tmp_path):
    """build_fixture.build is what regenerates corpus.jsonl: latest title and body, the
    state each record ended in, removed and closed records kept, every text redacted."""
    sys.path.insert(0, str(FIXTURE))
    try:
        build = importlib.import_module("build_fixture")
    finally:
        sys.path.remove(str(FIXTURE))
    lan = ".".join(("10", "9", "8", "7"))
    events = [
        ("task.added", "T1", {"title": "first title", "body": "old body"}),
        ("task.updated", "T1", {"body": f"new body naming {lan}"}),
        ("item.started", "T1", {}),
        ("item.completed", "T1", {}),
        ("task.added", "T2", {"title": "gone", "body": ""}),
        ("task.removed", "T2", {"reason": "duplicate"}),
        ("phase.added", "P1", {"title": "a phase", "body": ""}),
        ("bug.found", "B1", {"summary": "served as acme/Qwen9.9-99B-it"}),
        ("bug.fixed", "B1", {"regression_test": "t"}),
        ("bug.invalid", "B1", {"reason": "late"}),
        ("bug.found", "B2", {"summary": "a false finding"}),
        ("bug.invalid", "B2", {"reason": "not a bug"}),
        ("bug.found", "B3", {"summary": ""}),
    ]
    lines = [
        json.dumps(
            {
                "lamport": n,
                "agent": "a",
                "id": f"e{n}",
                "kind": k,
                "subject": s,
                "data": d,
                "ts": f"2026-10-01T00:00:{n:02d}Z",
            }
        )
        for n, (k, s, d) in enumerate(events)
    ]
    (tmp_path / "a.jsonl").write_text("\n".join([*lines, "{torn"]) + "\n", encoding="utf-8")
    recs = {r["id"]: r for r in build.build(tmp_path)}
    assert set(recs) == {"T1", "T2", "P1", "B1", "B2"}, "a bug with no text is not a record"
    assert recs["T1"]["title"] == "first title" and recs["T1"]["state"] == "done"
    assert recs["T1"]["body"] == "new body naming <lan-address>"
    assert recs["T1"]["added"] == "2026-10-01T00:00:00Z"
    assert recs["T2"]["state"] == "removed" and recs["P1"]["kind"] == "phase"
    assert recs["B1"]["state"] == "fixed", "a fix outranks a later invalid closure"
    assert recs["B1"]["body"] == "served as <served-model>"
    assert recs["B2"]["state"] == "invalid"


# --------------------------------------------------------------------------- evaluation


def evaluate(score_pairs) -> dict[str, float]:
    """Score every query the fixture implies and compute the bar's four metrics.

    ``score_pairs(query_id, candidate_ids) -> {candidate_id: score}`` scores the earlier
    records of the query's group; a candidate it leaves out scores 0. Ranks are
    pessimistic: a tie with the target counts against it, so a constant scorer fails."""
    ordered = sorted(CORPUS, key=_order)
    earlier: dict[str, list[str]] = {}
    seen: dict[str, list[str]] = collections.defaultdict(list)
    for r in ordered:
        earlier[r["id"]] = list(seen[_group(r)])
        seen[_group(r)].append(r["id"])
    scores = {q: score_pairs(q, cands) for q, cands in earlier.items() if cands}

    def pair_score(a: str, b: str) -> tuple[str, str, float]:
        q, t = (a, b) if _order(BY_ID[a]) > _order(BY_ID[b]) else (b, a)
        return q, t, scores.get(q, {}).get(t, 0.0)

    def rank(a: str, b: str) -> int:
        q, t, s = pair_score(a, b)
        return 1 + sum(1 for c in earlier[q] if c != t and scores[q].get(c, 0.0) >= s)

    by_rel = {rel: [(p["a"], p["b"]) for p in PAIRS if p["relation"] == rel] for rel in RELATIONS}
    positive = {frozenset(x) for rel in ("duplicate", "related") for x in by_rel[rel]}
    asked = [
        (q, c) for q, cs in scores.items() for c, s in cs.items() if c != q and s >= ASK_THRESHOLD
    ]
    dup_asked = sum(pair_score(a, b)[2] >= ASK_THRESHOLD for a, b in by_rel["duplicate"])
    return {
        "dup_r3": sum(rank(a, b) <= 3 for a, b in by_rel["duplicate"]) / len(by_rel["duplicate"]),
        "rel_r5": sum(rank(a, b) <= 5 for a, b in by_rel["related"]) / len(by_rel["related"]),
        "lenient_p": (sum(frozenset(x) in positive for x in asked) / len(asked) if asked else 0.0),
        "hard_above": sum(pair_score(a, b)[2] >= ASK_THRESHOLD for a, b in by_rel["hard_negative"])
        / len(by_rel["hard_negative"]),
        "dup_asked": dup_asked / len(by_rel["duplicate"]),
    }


def assert_meets_the_bar(m: dict[str, float]) -> None:
    shown = {k: round(v, 3) for k, v in m.items()}
    assert m["dup_r3"] >= BAR["dup_r3"], shown
    assert m["rel_r5"] >= BAR["rel_r5"], shown
    assert m["dup_asked"] >= MIN_DUP_ASKED, shown
    assert m["lenient_p"] >= BAR["lenient_p"], shown
    assert m["hard_above"] <= BAR["hard_above"], shown


def test_a_scorer_that_knows_nothing_fails_the_bar():
    """The metric code can fail: a constant scorer ties everything and asks on nothing."""
    m = evaluate(lambda q, cands: dict.fromkeys(cands, 0.5))
    assert m["dup_r3"] < BAR["dup_r3"] and m["dup_asked"] == 0.0


# The research's matcher (R-dedupe-matchers): stdlib TF-IDF cosine, sublinear tf, a
# code-aware word split, a light suffix stemmer, record ids and shas masked. A reference
# only -- the engine is free to differ as long as it clears the same bar.
_ID = re.compile(r"\b(?:[BRLDM][0-9a-f]{10}|[0-9a-f]{7,40})\b")
_IMPORTED = re.compile(r"Imported from \S+\.")
_STOP = frozenset(
    """a an the and or but if then else of to in on at by for with from as is are was were
    be been being it its this that these those there here not no nor so than too very can
    could should would will shall may might must do does did done has have had having which
    who whom whose what when where why how all any both each few more most other some such
    only own same just also into over under again further once out up down off about above
    below between through during before after while because until we you he she they them
    our your their his her my me us one two via per vs eg ie etc""".split()
)
_SUFFIXES = ("ations", "ation", "ings", "ing", "edly", "ed", "ies", "es", "ly", "s")


def _stem(w: str) -> str:
    if len(w) <= 4:
        return w
    for s in _SUFFIXES:
        if w.endswith(s) and len(w) - len(s) >= 3:
            return w[: -len(s)] + ("y" if s == "ies" else "")
    return w


def _tokens(rec: dict) -> list[str]:
    text = _ID.sub(" ", _IMPORTED.sub(" ", f"{rec['title']}. {rec['body']}"))
    out = []
    for w in re.findall(r"[A-Za-z][A-Za-z0-9]+", text):
        for part in re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", w).lower().split():
            if len(part) >= 2 and part not in _STOP:
                out.append(_stem(part))
    return out


def _reference_scorer():
    toks = {r["id"]: _tokens(r) for r in CORPUS}
    df = collections.Counter(t for ts in toks.values() for t in set(ts))
    n = len(CORPUS)
    idf = {t: math.log((1 + n) / (1 + c)) + 1 for t, c in df.items()}
    vecs = {}
    for rid, ts in toks.items():
        v = {t: (1 + math.log(c)) * idf[t] for t, c in collections.Counter(ts).items()}
        norm = math.sqrt(sum(x * x for x in v.values())) or 1.0
        vecs[rid] = {t: x / norm for t, x in v.items()}

    def score(q: str, cands: list[str]) -> dict[str, float]:
        a = vecs[q]
        return {c: sum(x * vecs[c].get(t, 0.0) for t, x in a.items()) for c in cands}

    return score


def test_the_reference_matcher_meets_the_bar():
    assert_meets_the_bar(evaluate(_reference_scorer()))


