def kinds(log: EventLog, kind: str) -> list[Event]:
    return [e for e in log.read_all() if e.kind == kind]


def stamp_newer(repo: Path, version: str = "99.0.0", agent: str = "future") -> None:
    """A log a NEWER ddflow has worked on: its stamp, in its own shard, as a merge brings it."""
    shard = repo / ".ddflow" / "events"
    shard.mkdir(parents=True, exist_ok=True)
    ev = Event(
        kind="ddflow.seen",
        subject="ddflow",
        data={"version": version, "install": "installed"},
        agent=agent,
        lamport=1,
        ts="2099-01-01T00:00:00.000000Z",
    )
    ev = Event(**{**ev.__dict__, "id": ev.compute_id()})
    with (shard / f"{agent}.jsonl").open("a") as fh:
        fh.write(ev.to_json() + "\n")


@pytest.fixture
def older_than_log(repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The running ddflow is OLDER than the log's highest stamp."""
    stamp_newer(repo)
    return repo


# -- versions ----------------------------------------------------------------------------


def test_versions_compare_as_numbers_not_text():
    assert version_key("0.1.10") > version_key("0.1.9")
    assert is_older("0.1.9", "0.1.10")
    assert not is_older("0.1.10", "0.1.10")
    assert not is_older("unknown", "0.1.10")  # an unparsable version is never a reason to refuse
    assert not is_older("0.1.10", "")
    # Two spellings of one release are one release; a pre-release is older than its release.
    assert not is_older("0.2", "0.2.0") and not is_older("0.2.0", "0.2")
    assert is_older("0.2.0rc1", "0.2.0") and not is_older("0.2.0", "0.2.0rc1")
    assert is_older("0.2.0rc1", "0.2.0rc2") and is_older("0.1.10", "0.2.0rc1")
    assert is_older("0.2.0.dev3", "0.2.0a1") and is_older("0.2.0a5", "0.2.0b1")
    assert is_older("0.2.0b2", "0.2.0rc1") and not is_older("0.2.0rc1", "0.2.0.dev3")
    assert version_key("v0.2.0") == version_key("0.2.0") and version_key("dev") == ()


# -- the stamp ---------------------------------------------------------------------------


def test_first_write_stamps_the_version_once_per_agent_and_version(repo: Path):
    log = EventLog(repo, "a1")
    log.append("phase.added", "P1", {"title": "p"})
    log.append("phase.added", "P2", {"title": "p"})
    seen = kinds(log, "ddflow.seen")
    assert len(seen) == 1
    assert seen[0].data["version"] == ddflow.__version__
    assert seen[0].data["install"]
    # The stamp precedes the event that caused it.
    order = [e.kind for e in log.read_all()]
    assert order[:2] == ["ddflow.seen", "phase.added"]
    # A second agent stamps its own first write, and a new process of the same agent does not.
    EventLog(repo, "a2").append("phase.added", "P3", {"title": "p"})
    EventLog(repo, "a1").append("phase.added", "P4", {"title": "p"})
    assert sorted(e.agent for e in kinds(log, "ddflow.seen")) == ["a1", "a2"]


def test_a_new_version_stamps_again_and_the_fold_keeps_the_highest(
    repo: Path, monkeypatch: pytest.MonkeyPatch
):
    monkeypatch.setattr(ddflow, "__version__", "0.1.9")
    log = EventLog(repo, "a1")
    log.append("phase.added", "P1", {"title": "p"})
    monkeypatch.setattr(ddflow, "__version__", "0.1.10")
    log.append("phase.added", "P2", {"title": "p"})
    # An older ddflow stamping after a newer one (policy off) does not lower the project's version.
    assert [e.data["version"] for e in kinds(log, "ddflow.seen")] == ["0.1.9", "0.1.10"]
    st = fold(log.read_all())
    assert st.highest_version == "0.1.10"
    assert set(st.ddflow_versions) == {"0.1.9", "0.1.10"}
    assert st.ddflow_versions["0.1.10"]["agents"] == ["a1"]


def test_stamp_writes_the_local_marker(repo: Path):
    EventLog(repo, "a1").append("phase.added", "P1", {"title": "p"})
    marker = json.loads((repo / ".ddflow" / "local" / "seen.json").read_text())
    assert marker["version"] == ddflow.__version__
    assert (repo / ".ddflow" / "local" / ".gitignore").read_text().strip() == "*"


def test_an_old_unstamped_log_reads_clean_and_is_stamped_on_first_write(repo: Path):
    events = repo / ".ddflow" / "events"
    events.mkdir(parents=True)
    shutil.copy(FIXTURE, events / "fx013.jsonl")
    log = EventLog(repo, "fx013")
    before = fold(log.read_all())  # strict: nothing in a 0.1.3 log is unknown to this code
    assert before.skipped_kinds == {} and before.highest_version == ""
    assert not log.verify()
    log.append("phase.added", "P2", {"title": "second"})
    after = fold(log.read_all())
    assert after.highest_version == ddflow.__version__
    assert {"P1", "P2"} <= set(after.items)


def test_a_fresh_project_is_stamped_by_ddflow_init_and_first_add(repo: Path):
    assert run_cli(repo, "init")[0] == 0
    assert run_cli(repo, "phase", "add", "P1", "--title", "p")[0] == 0
    st = fold(EventLog(repo).read_all())
    assert st.highest_version == ddflow.__version__


# -- what an older reader does with the new kinds ----------------------------------------


def test_an_older_reader_skips_the_new_kinds_with_a_count_not_an_error(
    repo: Path, monkeypatch: pytest.MonkeyPatch
):
    log = EventLog(repo, "a1")
    log.append("phase.added", "P1", {"title": "p"})
    events = log.read_all()
    assert any(e.kind == "ddflow.seen" for e in events)
    # A 0.1.3-like vocabulary: no stamp kinds.
    old = {
        k: v
        for k, v in M.HANDLERS.items()
        if k not in ("ddflow.seen", "skew.overridden", "upgrade.applied")
    }
    monkeypatch.setattr(M, "HANDLERS", old)
    st = fold(events, strict=False)
    assert st.skipped_kinds == {"ddflow.seen": 1}
    assert "P1" in st.items
    with pytest.raises(ValueError):
        fold(events, strict=True)


def test_an_event_with_a_newer_schema_is_counted_like_a_skipped_kind():
    e = Event(kind="phase.added", subject="P1", data={"title": "p"}, lamport=1, schema=99)
    st = fold([e], strict=False)
    assert st.items == {}
    assert st.skipped_kinds == {"phase.added (schema 99)": 1}


