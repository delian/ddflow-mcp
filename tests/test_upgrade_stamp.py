def test_doctor_advice_for_skipped_kinds_is_to_upgrade(repo: Path):
    shard = repo / ".ddflow" / "events"
    shard.mkdir(parents=True)
    e = Event(
        kind="future.kind",
        subject="X",
        data={},
        agent="future",
        lamport=1,
        ts="2099-01-01T00:00:00Z",
    )
    e = Event(**{**e.__dict__, "id": e.compute_id()})
    (shard / "future.jsonl").write_text(e.to_json() + "\n")
    stamp_newer(repo, "99.0.0", agent="future")
    _code, out, _err = run_cli(repo, "doctor")
    assert "future.kind x1" in out
    # The remedy fits how this ddflow is installed (B-uni-compat-config): a source checkout
    # merges main, an installed one upgrades its package.
    if II.install_info().kind in ("source-tree", "editable"):
        assert "Merge main" in out and "Upgrade ddflow-mcp to" not in out
    else:
        assert "Upgrade ddflow-mcp to >= 99.0.0" in out and "Merge main" not in out


