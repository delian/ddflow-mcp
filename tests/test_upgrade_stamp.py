def _mcp(repo: Path, name: str, args: dict):
    from ddflow.surfaces.mcp import Server

    reply = Server(repo).handle(
        {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "tools/call",
            "params": {"name": name, "arguments": args},
        }
    )
    return reply["result"]


def test_mcp_refuses_with_exit_3_then_accepts_the_override_argument(older_than_log: Path):
    res = _mcp(older_than_log, "ddflow_phase_add", {"id": "P1", "title": "p", "as_agent": "me"})
    assert res["_meta"]["exit"] == 3, res
    assert "Upgrade ddflow-mcp to >= 99.0.0" in res["content"][0]["text"]
    res = _mcp(
        older_than_log,
        "ddflow_phase_add",
        {"id": "P1", "title": "p", "as_agent": "me", "allow_older_version": "operator said go"},
    )
    assert not res.get("isError"), res
    assert kinds(EventLog(older_than_log, "me"), "skew.overridden")[0].data["reason"] == (
        "operator said go"
    )
    # Reads are never refused.
    assert not _mcp(older_than_log, "ddflow_status", {"as_agent": "other"}).get("isError")


