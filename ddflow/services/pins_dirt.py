"""The owner of uncommitted pin files that block a merge (B8f12fe0f03)."""

from __future__ import annotations

import shlex
from pathlib import Path

from ..config import Config
from .pins import pin_files

_OVERWRITTEN = "would be overwritten by merge"


def dirt_hint(repo: Path, cfg: Config, git_error: str, tree: Path) -> str:
    """Who owns the uncommitted files that made git refuse a merge (B8f12fe0f03).

    git names the locally modified files it would overwrite. A PIN file among them is
    derived output (a stray `ddflow pins regenerate` run in the primary tree), which no
    other tool cleans up; say so and say how to look at it and discard it. Empty when the
    refusal is not that one, or names no pin file."""
    lines = git_error.splitlines()
    tracked: list[str] = []
    untracked: list[str] = []
    for i, line in enumerate(lines):
        if _OVERWRITTEN not in line:
            continue
        into = untracked if "untracked" in line else tracked
        for nxt in lines[i + 1 :]:
            if not nxt[:1].isspace():
                break
            into.append(nxt.strip())
    pins = set(pin_files(repo, cfg))
    mine = [f for f in tracked if f in pins]
    loose = [f for f in untracked if f in pins]
    if not mine and not loose:
        return ""
    where = shlex.quote(str(tree))
    out = ""
    if mine:
        files = " ".join(shlex.quote(f) for f in mine)
        out += (
            f"\n\n{', '.join(mine)} {'is a pin file' if len(mine) == 1 else 'are pin files'} "
            f"(regenerated by `ddflow pins regenerate`), and {tree} holds an uncommitted change to "
            f"{'it' if len(mine) == 1 else 'them'}: most likely a stray regenerate run there, which "
            f"no other tool cleans up. See what it is: `git -C {where} diff HEAD -- {files}`. If it "
            f"is only regenerated output, discard it: `git -C {where} checkout HEAD -- {files}`, "
            "then merge again; if it is a real edit, commit it first."
        )
    if loose:
        names = " ".join(shlex.quote(f) for f in loose)
        out += (
            f"\n\n{', '.join(loose)} is an untracked pin file in {tree} (a stray `ddflow pins "
            f"regenerate` wrote it there): move it aside (`mv` in {where}: {names}) and merge again."
        )
    return out
