"""Human-readable projections: boards, lessons, and the session brief.

Every file this module writes is **generated** and carries a header saying so. None is
ever parsed back. That single rule removes the entire failure family the projects that
inspired ddflow spent years fighting: markdown that is simultaneously a human document
and a machine record drifts, because humans edit prose and machines edit structure, and
neither notices the other. Here the log is the record and the markdown is a view, so a
stale view is repaired by regenerating it, never by reconciling it.

``brief`` is the load-bearing one. An agent starting a session needs the rules that
apply, the task at hand, and the handful of past lessons that bear on it — and needs
them in roughly a thousand tokens, not the fifteen thousand that reading the corpora
costs. It is retrieval, budgeted, with the budget enforced rather than hoped for.
"""

from __future__ import annotations

