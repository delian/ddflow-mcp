"""Admission: may this item (or these globs) start beside what is already going?

One place for the glob-overlap question that `item_blocker` (the plan's live-lease check),
`leases.glob_clash` (`claim` and `update --globs`), `schedule._offered_overlap` (two items
offered in one plan) and the waiter reservation each asked with their own copy of the same
loop: skip your own, skip a different release line, then `conflicts` against the shared
globs. The copies were identical by hand; this makes them identical by construction.

Pure: no I/O and no clock. ``cfg`` is the project `Config` (typed ``Any`` because `core`
sits below `config` in the layers).
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any, Literal

from ..core.model import Item, Lease, State
from .flow import line_key
from .globs import match as glob_match
from .globs import overlap as globs_overlap


def shared_globs(cfg: Any) -> list[str]:
    """`[lease] shared_globs` and `append_only_globs`: paths many items may hold at once
    (D-shared-globs), plus every SELECTED export target (D-export (2)): a generated document
    is regenerated by whoever runs `ddflow export`, so no claim on it is needed. A `region`
    target is a hand-written file with a generated region; it is shared for the same reason."""
    lease = cfg.lease
    return [
        *lease.shared_globs,
        *lease.append_only_globs,
        *(p for _d, p, _m in cfg.export.targets()),
    ]


def new_file_globs(cfg: Any) -> list[str]:
    """`[lease] new_file_globs`: files an item adds under its own name (an upgrade-manifest
    fragment). Never exempt from lease overlap (a lease on an existing fragment stays exclusive); the commit hook covers a staged NEW
    file matching one for any live lease holder, never an edit of an existing one."""
    return list(cfg.lease.new_file_globs)


def is_shared(glob: str, shared: list[str]) -> bool:
    """Is ``glob`` (a claim's glob or a staged path) INSIDE one of the ``shared`` globs?

    Inside, not overlapping: `docs/**` merely overlaps a shared `docs/CHANGELOG.md` and
    still claims the rest of `docs/`, so it stays exclusive. Matched as git matches the
    `.gitattributes` line (`core.globs`), so "shared" and "merged with union" agree.
    """
    return any(glob_match(glob, s, bare_any_depth=True) for s in shared)


def conflicts(
    mine: list[str], theirs: list[str], shared: list[str] | None = None
) -> list[tuple[str, str]]:
    """Overlapping pairs between two glob lists; a glob inside ``shared`` overlaps nothing.

    Every parallel item edits a changelog; exclusive leases on it serialised them all
    or pushed agents to commit it unleased (B07878037ab).
    """
    shared = shared or []
    mine = [a for a in mine if not is_shared(a, shared)]
    theirs = [b for b in theirs if not is_shared(b, shared)]
    return [(a, b) for a in mine for b in theirs if globs_overlap(a, b)]


def real_overlap(
    mine: list[str],
    theirs: list[str],
    changed: list[str] | None,
    shared: list[str] | None = None,
) -> list[tuple[str, str]]:
    """Overlapping pairs once the holder's ACTUAL changes are compared (DX-lease-real-overlap).

    ``theirs`` are the holder's declared claim globs; ``changed`` are the paths its worktree
    actually changed (git diff against base) plus its literal declared paths. ``changed is
    None`` means git could not say (no worktree, unreadable): unknown is never "disjoint",
    so the answer falls back to the prefix rule (`conflicts`).

    Only a WILDCARD glob in ``theirs`` can cover files its holder never touches; that pair
    survives only when an actually-changed path sits under BOTH ``mine`` and ``theirs``
    (it really is ``theirs``'s work, not another of the holder's globs). An exact
    (wildcard-free) ``theirs`` path is declared work -- changed yet or not -- so it always
    overlaps. ``shared`` globs overlap nothing, exactly as in `conflicts`.
    """
    pairs = conflicts(mine, theirs, shared)
    if changed is None:
        return pairs
    shared = shared or []
    real = [p for p in changed if not is_shared(p, shared)]
    return [
        (a, b)
        for a, b in pairs
        # A changed path must fall under BOTH globs: under the holder's glob ``b`` (it
        # really is this glob's work, not another of the holder's globs) and under the
        # claimant's glob ``a`` (the file this pair could actually collide on).
        if not any(c in b for c in "*?[")
        or any(glob_match(p, a) and glob_match(p, b) for p in real)
    ]


def queued_globs(mine: list[str], theirs: list[str], cfg: Any) -> list[str]:
    """The ``mine`` globs that ``theirs`` overlaps (shared globs excluded): one name per
    queued-behind clause, so the refusal names it instead of the whole ``theirs`` list."""
    return list(dict.fromkeys(m for m, _t in conflicts(mine, theirs, shared_globs(cfg))))


@dataclass(frozen=True)
class Clash:
    """One overlapping pair with another item ``globs`` would collide on, and whose."""

    item: str
    pair: tuple[str, str]
    #: The overlapped item's live lease; ``None`` when it is merely offered or reserved.
    lease: Lease | None = None


def glob_clashes(
    state: State,
    cfg: Any,
    it: Item,
    globs: list[str],
    holder: str = "",
    *,
    against: Literal["live", "offered"] = "live",
    live: dict[str, Lease] | None = None,
    others: Iterable[Item] = (),
) -> list[Clash]:
    """Every overlapping pair another item's globs have with ``globs`` (``glob_conflict``
    stops at the first). One other item that overlaps on more than one glob yields one
    `Clash` per pair, so a refusal built from the list names every held glob instead of
    the first (B-glob-refusal-names-one-conflict).

    ``against="live"``: the live leases ``live`` (item id -> lease), skipping ``it``'s own
    and any held by ``holder`` (one author cannot collide with itself).
    ``against="offered"``: the items ``others`` (already offered in one plan, or the item a
    waiter is queued for), skipping ``it`` itself should it be among them.

    Items on different release lines are different branches: `src/x.py` on 2.x and on 3.x
    cannot collide, and refusing it would serialise every port behind its fix.
    ``shared_globs`` overlap nothing.
    """
    mine = line_key(state, it, cfg)
    shared = shared_globs(cfg)
    out: list[Clash] = []
    if against == "live":
        for other_id, lease in (live or {}).items():
            if other_id == it.id or lease.holder == holder:
                continue
            other = state.items.get(other_id)
            if other is not None and line_key(state, other, cfg) != mine:
                continue
            pairs = conflicts(globs, lease.globs, shared)
            out.extend(Clash(other_id, pair, lease) for pair in pairs)
        return out
    for other in others:
        if other.id == it.id or line_key(state, other, cfg) != mine:
            continue
        pairs = conflicts(globs, list(other.globs), shared)
        out.extend(Clash(other.id, pair) for pair in pairs)
    return out


def glob_conflict(
    state: State,
    cfg: Any,
    it: Item,
    globs: list[str],
    holder: str = "",
    *,
    against: Literal["live", "offered"] = "live",
    live: dict[str, Lease] | None = None,
    others: Iterable[Item] = (),
) -> Clash | None:
    """The first other item whose globs overlap ``globs``, or ``None`` when none does.

    See `glob_clashes` for the rules; this is its first result.
    """
    clashes = glob_clashes(state, cfg, it, globs, holder, against=against, live=live, others=others)
    return clashes[0] if clashes else None
